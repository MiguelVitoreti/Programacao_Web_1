/*

Operadores Relacionais
== : igual (valor)
=== : estritamente igual (valor e tipo)
!= : diferente (valor)
!== : estritamente diferente (valor e tipo)
> : maior que
< : menor que
>= : maior ou igual que
<= : menor ou igual que

*/

//Exemplo

let num1 = 7
let num2 = "7"
let num3 = 3

//igual
console.log(num1 == num2) 

//estritamente igual
console.log(num1 === num2)

//diferente
console.log(num1 != num2)

//estritamente diferente
console.log(num1 !== num2)

//maior 
console.log(num1 > num3)

//menor 
console.log(num1 < num3)

//maior ou igual 
console.log(num1 >= num3)

//menor ou igual 
console.log(num1 <= num3)